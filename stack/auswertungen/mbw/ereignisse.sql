SELECT wbz.NUMMER     "Wahlbezirknummer",
       e.UHRZEIT      "Ereignisuhrzeit",
       e.EREIGNISART  "Vorfall oder Vorkommnis",
       e.BESCHREIBUNG "Beschreibung",
       wbz.WAHLBEZIRKID
FROM WLS_BASISDATEN_SERVICE.WAHLBEZIRK wbz
         INNER JOIN WLS_VORFAELLEUNDVORKOMMNISSE_SERVICE.EREIGNIS E ON wbz.WAHLBEZIRKID = E.EREIGNISSE_WAHLBEZIRKID
ORDER BY wbz.NUMMER, e.UHRZEIT
;