SELECT wbz.NUMMER          "Wahlbezirknummer",
       v.BLATTNUMMER       "Blattnummer",
       VStimmzettel.ANZAHL "Anzahl",
       wbz.WAHLBEZIRKID
FROM WLS_BASISDATEN_SERVICE.WAHLBEZIRK wbz
         LEFT JOIN WLS_ERGEBNISMELDUNG_SERVICE.VERMERK V ON wbz.WAHLBEZIRKID = v.FK_WAHLBEZIRKID
         LEFT JOIN WLS_ERGEBNISMELDUNG_SERVICE.STIMMABGABEVERMERKESTIMMZETTEL VStimmzettel
                   On V.ID = VStimmzettel.VERMERKID
WHERE wbz.WAHLBEZIRKART = 'UWB'
ORDER by wbz.NUMMER, v.BLATTNUMMER
;