SELECT wbz.NUMMER "Wahlbezirknummer",
       ZURUECKWEISEGRUENDE.ZURUECKWEISEGRUENDE,
       wbz.WAHLBEZIRKID
FROM WLS_BASISDATEN_SERVICE.WAHLBEZIRK wbz
         LEFT JOIN WLS_BRIEFWAHL_SERVICE.BEANSTANDETEWAHLBRIEFE beanstanded
                   ON wbz.WAHLBEZIRKID = beanstanded.WAHLBEZIRKID
         INNER JOIN WLS_BRIEFWAHL_SERVICE.ZURUECKWEISEGRUENDE
                    on beanstanded.WAHLBEZIRKID = ZURUECKWEISEGRUENDE.BW_WAHLBEZIRKID and
                       beanstanded.WAEHLERVERZEICHNISNUMMER = ZURUECKWEISEGRUENDE.BW_WAEHLERVERZEICHNISNUMMER
WHERE wbz.WAHLBEZIRKART = 'BWB'
ORDER BY wbz.NUMMER
;