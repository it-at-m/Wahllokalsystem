CREATE TABLE Revinfo
(
    rev INT GENERATED BY DEFAULT
        AS IDENTITY ( START WITH 1 ),
    revtstmp BIGINT NOT NULL,

    constraint pk_revinfo PRIMARY KEY (rev)
);

CREATE TABLE Stimmzettel_AUD
(
    rev INT NOT NULL,
    revtype INT NOT NULL,
    wahlbezirkID       VARCHAR(255) NOT NULL,
    wahlID             VARCHAR(255) NOT NULL,
    teamID             VARCHAR(255) NOT NULL,
    stimmzettelkennung INT          NOT NULL,
    invalideVotes      INT          NOT NULL,
    gueltigkeit        VARCHAR(255) NOT NULL,
    beschluss_pro      INT,
    beschluss_contra   INT,
    beschluss_text     varchar(255),
    CONSTRAINT pk_stimmzettel_aud PRIMARY KEY (rev, wahlbezirkID, wahlID, teamID, stimmzettelkennung)
);

CREATE TABLE WahlvorstandBeschlussgrund_AUD
(
    rev INT NOT NULL,
    revtype INT NOT NULL,
    id                             VARCHAR(255) NOT NULL,
    text                           VARCHAR(100) NOT NULL,
    stimmzettel_wahlbezirkID       VARCHAR(255) ,
    stimmzettel_wahlID             VARCHAR(255)  ,
    stimmzettel_teamID             VARCHAR(255)  ,
    stimmzettel_stimmzettelkennung INT           ,
    CONSTRAINT pk_wahlvorstandbeschlussgrund_aud PRIMARY KEY (rev, id)
);

CREATE TABLE SystemBeschlussgrund_AUD
(
    rev INT NOT NULL,
    revtype INT NOT NULL,
    id                             VARCHAR(255) NOT NULL,
    reason                         VARCHAR(100),
    stimmzettel_wahlbezirkID       VARCHAR(255) ,
    stimmzettel_wahlID             VARCHAR(255) ,
    stimmzettel_teamID             VARCHAR(255) ,
    stimmzettel_stimmzettelkennung INT          ,
    CONSTRAINT pk_systemBeschlussgrund_aud PRIMARY KEY (rev, id)
);

CREATE TABLE Wahlvorschlag_AUD
(
    rev INT NOT NULL,
    revtype INT NOT NULL,
    id                             VARCHAR(255) NOT NULL,
    wahlvorschlagID                VARCHAR(255),
    selected                       BOOLEAN      ,
    stimmzettel_wahlbezirkID       VARCHAR(255),
    stimmzettel_wahlID             VARCHAR(255),
    stimmzettel_teamID             VARCHAR(255),
    stimmzettel_stimmzettelkennung INT    ,
    CONSTRAINT pk_wahlvorschlag_aud PRIMARY KEY (rev, id)
);

CREATE TABLE Kandidat_AUD
(
    rev INT NOT NULL,
    revtype INT NOT NULL,
    id                   VARCHAR(36)  NOT NULL,
    kandidatID           VARCHAR(255),
    nennungsNummer       INT          ,
    wahlvorschlag_id     VARCHAR(255),
    discarded            BOOLEAN      ,
    votesByVoter         INT,
    invalidVotes         INT,
    votesByWahlvorschlag INT,
    PRIMARY KEY (rev, id)
);
